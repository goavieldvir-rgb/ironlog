#!/usr/bin/env bash
# Copies the rendered exercise clips into the app and writes the manifest the
# app reads (src/lib/clipManifest.js). Run it again after a re-render; each
# file's version is a hash of its bytes, so phones fetch only clips that
# changed and keep the rest cached.
#
#   scripts/sync-clips.sh [ANIMATIONS_OUT_DIR]
#   ONLY=slug,slug scripts/sync-clips.sh   just these clips, the rest untouched
#
# Use ONLY when a single clip was re-rendered and approved: the render output
# often holds other re-renders that are still waiting for review.
#
# ANIMATIONS_OUT_DIR defaults to the project's shared render output:
#   <dir>/exercises-v2/<slug>.mp4                  main clip (720x720 loop)
#   <dir>/technique-tips/<slug>/<slug>-tips.mp4   technique tips (optional)
set -euo pipefail
SRC="${1:-/mnt/project-files/ironlog-animations/pipeline/out}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/public/clips"
MANIFEST="$ROOT/src/lib/clipManifest.js"
command -v ffmpeg >/dev/null || { echo "ffmpeg is required" >&2; exit 1; }

if [ -n "${ONLY:-}" ]; then
  files=()
  for slug in ${ONLY//,/ }; do
    [ -f "$SRC/exercises-v2/$slug.mp4" ] || { echo "No clip for $slug" >&2; exit 1; }
    files+=("$SRC/exercises-v2/$slug.mp4")
  done
else
  rm -rf "$OUT"
  files=("$SRC"/exercises-v2/*.mp4)
fi
mkdir -p "$OUT/tips"
entries=()
for f in "${files[@]}"; do
  slug="$(basename "$f" .mp4)"
  cp "$f" "$OUT/$slug.mp4"
  # Still for the icon: the peak of the rep, cropped tight around the figure,
  # 256 px square (sharp at 64 px on a 4x screen). Hand overrides are in
  # scripts/clip_stills.txt.
  args="$(awk -v s="$slug" '$1 == s { $1 = ""; print }' "$ROOT/scripts/clip_stills.txt")"
  # shellcheck disable=SC2086
  python3 -I "$ROOT/scripts/clip_still.py" "$f" "$OUT/$slug.jpg" $args >/dev/null
  v="$(cat "$OUT/$slug.mp4" "$OUT/$slug.jpg" | sha1sum | cut -c1-8)"
  tips=""
  t="$SRC/technique-tips/$slug/$slug-tips.mp4"
  if [ -f "$t" ]; then
    cp "$t" "$OUT/tips/$slug.mp4"
    tips=", t: '$(sha1sum < "$t" | cut -c1-8)'"
  fi
  entries+=("  '$slug': { v: '$v'$tips },")
done

if [ -n "${ONLY:-}" ]; then
  # Swap just these slugs' lines in the existing manifest.
  for e in "${entries[@]}"; do
    slug="$(echo "$e" | sed -E "s/^  '([^']+)'.*/\1/")"
    grep -q "^  '$slug':" "$MANIFEST" || { echo "$slug is not in the manifest; run a full sync" >&2; exit 1; }
    E="$e" S="$slug" python3 -I -c 'import os,re,sys; p=sys.argv[1]; t=open(p).read(); t=re.sub(r"^  \x27"+re.escape(os.environ["S"])+r"\x27:.*$", lambda m: os.environ["E"], t, flags=re.M); open(p,"w").write(t)' "$MANIFEST"
  done
  echo "Synced ${#entries[@]} clip(s): $ONLY"
  exit 0
fi

{
  echo "// Generated by scripts/sync-clips.sh. Do not edit by hand."
  echo "// slug -> { v: version of the clip and its still, t: version of the technique-tips clip }"
  echo "export const CLIPS = {"
  printf '%s\n' "${entries[@]}"
  echo "}"
} > "$MANIFEST"
echo "Synced ${#entries[@]} clips ($(ls "$OUT"/tips | wc -l) with technique tips) -> public/clips, $(du -sh "$OUT" | cut -f1)"
